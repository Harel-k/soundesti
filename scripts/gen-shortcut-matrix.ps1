# Regenerates docs/SHORTCUT_MATRIX.md from assets/shortcuts/fl-studio-workflow.toml
# and assets/shortcuts/status.toml. Run after changing either file.
$root = Split-Path $PSScriptRoot -Parent
$status = @{}
Get-Content "$root\assets\shortcuts\status.toml" | ForEach-Object {
    if ($_ -match '^"([^"]+)"\s*=\s*"([A-Z_]+)"') { $status[$Matches[1]] = $Matches[2] }
}
$rows = @()
Get-Content "$root\assets\shortcuts\fl-studio-workflow.toml" | ForEach-Object {
    if ($_ -match '\{\s*ctx\s*=\s*"([^"]+)",\s*keys\s*=\s*"([^"]+)",\s*cmd\s*=\s*"([^"]+)"(.*)\}') {
        # Copy the groups first: every later -match overwrites $Matches.
        $ctx = $Matches[1]; $keys = $Matches[2]; $cmd = $Matches[3]; $rest = $Matches[4]
        $arg = if ($rest -match 'arg\s*=\s*(-?\d+)') { $Matches[1] } else { "" }
        $section = if ($rest -match 'section\s*=\s*"([^"]+)"') { $Matches[1] } else { "" }
        $s = if ($status.ContainsKey($cmd)) { $status[$cmd] } else { "PLANNED" }
        if ($keys -match "^(Alt\+)?Num" -and $s -ne "PLANNED") { $s = "BLOCKED" }
        $rows += [pscustomobject]@{ Ctx = $ctx; Keys = $keys; Cmd = $cmd; Arg = $arg; Section = $section; Status = $s }
    }
}
$counts = $rows | Group-Object Status | Sort-Object Name | ForEach-Object { "$($_.Name): $($_.Count)" }
$out = @()
$out += "# Shortcut matrix - FL Studio Workflow profile"
$out += ""
$out += "> Generated by ``scripts/gen-shortcut-matrix.ps1`` from ``assets/shortcuts/fl-studio-workflow.toml`` (the machine-readable source the app loads) and ``assets/shortcuts/status.toml``. Do not edit by hand."
$out += ""
$out += "Source: [FL Studio manual - shortcuts](https://www.image-line.com/fl-studio-learning-content/fl-studio-online-manual/html/basics_shortcuts.htm), fetched 2026-10-24. Every keyboard row on that page is present; mouse gestures are tracked in MOUSE_GESTURES.md."
$out += ""
$out += "**Totals ($($rows.Count) bindings):** $($counts -join ' | ')"
$out += ""
$out += "Automated coverage: ``soundesti-shortcuts`` tests load this profile, reject conflicts, assert every row resolves to its own command in its context, check the master prompt's mandatory mappings, text-field suppression and typing-keyboard suppression."
$out += ""
$out += "## Notes"
$out += ""
$out += "- **SM-1 Numpad:** egui reports numpad digits as main-row digits, so ``Num...`` bindings cannot fire yet (KI-002). They are BLOCKED, not remapped, to keep this profile faithful."
$out += "- **SM-2 Left/right modifiers:** FL uses Left-Shift vs Right-Shift and Right-Alt for some mouse gestures. Not distinguishable yet (KI-002)."
$out += "- **SM-3 Quick quantize:** the manual lists ``Ctrl/Cmd+Opt+Q``; the master prompt lists ``Ctrl+Q``. Both are bound to Quick quantize."
$out += "- **SM-4 Playlist 5-9:** the manual does not say numpad; bound to the main digit row."
$out += "- **SM-5 Typing keyboard layout:** standard two-row tracker layout (Z-row lower octave, Q-row upper). Exact FL layout not yet verified."
$out += "- **SM-6 Text fields:** while a text field has focus only F1-F12 dispatch; everything else types. **Typing keyboard on:** single keys that are piano keys play notes; Space, F-keys, arrows and Ctrl/Alt chords still dispatch."
$out += ""
foreach ($g in ($rows | Group-Object Ctx)) {
    $out += "## Context: $($g.Name)"
    $out += ""
    $out += "| Keys | Command ID | Arg | Manual section | Status |"
    $out += "|---|---|---|---|---|"
    foreach ($r in $g.Group) { $out += "| ``$($r.Keys)`` | ``$($r.Cmd)`` | $($r.Arg) | $($r.Section) | $($r.Status) |" }
    $out += ""
}
New-Item -ItemType Directory -Force "$root\docs" | Out-Null
$out | Set-Content -Encoding utf8 "$root\docs\SHORTCUT_MATRIX.md"
"wrote docs/SHORTCUT_MATRIX.md ($($rows.Count) rows; $($counts -join ', '))"
